import type { CodegenConfig } from '@graphql-codegen/cli';

/**
 * Generates src/generated/graphql.ts from the server's schema and the
 * operations in src/operations. Run `npm run generate`; CI fails when the
 * committed output is stale (`npm run check`).
 */
const config: CodegenConfig = {
  schema: '../graphql-server/src/schema.graphql',
  documents: 'src/operations/**/*.graphql',
  generates: {
    'src/generated/graphql.ts': {
      plugins: [
        { add: { content: '/* eslint-disable */\n// Generated by `npm run generate` from graphql-server/src/schema.graphql. Do not edit.' } },
        // typescript-operations emits the enum and input types the operations
        // use; adding the `typescript` plugin as well declares them twice.
        'typescript-operations',
        'typed-document-node',
      ],
      config: {
        // String unions rather than TypeScript enums: no runtime code, and a
        // value the server adds later is a type error, not a silent mismatch.
        enumsAsTypes: true,
        // Documents as strings, so a consumer needs no `graphql` runtime.
        documentMode: 'string',
        useTypeImports: true,
        avoidOptionals: { field: true, inputValue: false, object: true, defaultValue: false },
        skipTypename: true,
      },
    },
  },
};

export default config;
